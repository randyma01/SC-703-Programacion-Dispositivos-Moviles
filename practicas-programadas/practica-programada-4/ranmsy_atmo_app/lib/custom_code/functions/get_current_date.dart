/// Returns formatted current date in Spanish.
String? getCurrentDate() {
  final now = DateTime.now();
  const days = [
    'Lunes',
    'Martes',
    'Miércoles',
    'Jueves',
    'Viernes',
    'Sábado',
    'Domingo'
  ];
  const months = [
    'enero',
    'febrero',
    'marzo',
    'abril',
    'mayo',
    'junio',
    'julio',
    'agosto',
    'septiembre',
    'octubre',
    'noviembre',
    'diciembre'
  ];
  final dayName = days[now.weekday - 1];
  final monthName = months[now.month - 1];
  return '$dayName, ${now.day} de $monthName';
}
